// Prints the UI's static market list for the corrected round-3 set, from the creation log.
//
// The UI (ai-prediction-markets, src/utils/originalityR3V3Markets.ts) cannot discover this set
// at runtime: MarketView reverts for the middle markets (see read-market.js), and a score
// market's parentOutcome is a slot in its middle market, which does not name the repo
// against the parent. So the addresses are generated once, here, and committed there.
//
// Reads no chain and sends nothing. Every address is lowercased, as the UI compares them.
//
//   node campaigns/originality-r3-v3/export-ui-markets.js > <ui repo>/src/utils/originalityR3V3Markets.ts

import fs from "fs";

const MARKETS_FILE = "campaigns/originality-r3-v3/create-originality-r3-v3-execution.json";
const SEED_FILE = "campaigns/originality-r3-v3/originality-r3-v3-seed.json";

const created = JSON.parse(fs.readFileSync(MARKETS_FILE, "utf8"));
const seed = JSON.parse(fs.readFileSync(SEED_FILE, "utf8"));
const lc = (a) => a.toLowerCase();

if (!created.parent?.wrappedTokens || created.parent.wrappedTokens.length !== 4) throw new Error("parent wrapped tokens missing");
if (created.middles.length !== 3 || created.middles.some((m) => !m.verified || !m.wrappedTokens)) throw new Error("middle markets incomplete or unverified");
if (created.children.length !== seed.children.length || created.children.some((c) => c.verified !== true)) {
  throw new Error("score markets incomplete or unverified");
}

const middles = seed.bundles.map((b) => {
  const m = created.middles.find((e) => e.parentOutcome === b.index);
  if (m.wrappedTokens.length !== b.repos.length + 1) throw new Error(`${b.label}: wrapped token count`);
  return m;
});
// In seed order, which is bundle order then slot order.
const rows = seed.children.map((c) => {
  const e = created.children.find((x) => x.repo === c.repo);
  if (!e) throw new Error(`${c.repo}: not in the creation log`);
  if (lc(e.parentMarket) !== lc(middles[c.parentOutcome].market)) throw new Error(`${c.repo}: parent market mismatch`);
  return { repo: c.repo, address: lc(e.market), bundle: c.parentOutcome, slot: c.indexInBundle };
});

const out = [];
out.push(`import { Address } from "viem";

/**
 * Round-3 Originality on Optimism, CORRECTED set: one multi-scalar parent, one multi-categorical
 * market per bundle beneath it, and 98 scalar repo markets beneath those. Created ${created.parent.timestamp.slice(0, 10)} and
 * seeded with 1,000 sUSDS. It replaces the set in \`./originalityR3Markets\`, which was created
 * without the middle level.
 *
 * Generated by \`campaigns/originality-r3-v3/export-ui-markets.js\` in the liquidity repo from its
 * creation log — do not edit by hand.
 *
 * THE THREE LEVELS. The parent asks "How many repositories in [bundle] will be evaluated…", with
 * outcomes Bundle A/B/C. Each bundle token is the collateral of a MIDDLE market, "Which
 * repositories in Bundle A will be evaluated…", whose outcomes are that bundle's repos. Each repo
 * token is in turn the collateral of that repo's score market. So a repo market is collateralized
 * in its OWN token, as in round 2, and sUSDS reaches it through two splits: parent, then middle.
 *
 * Static rather than discovered at runtime, for two reasons. \`MarketView.getMarket\` REVERTS for
 * the middle markets (it walks the parent's outcome list for as many slots as the child has, and a
 * middle market has 33 or 34 slots under a 3-outcome parent), so they must never be put in a
 * MarketView read. And a repo market's \`parentOutcome\` is its slot in its middle market, which
 * does not name the repo against the parent.
 *
 * This file is reached from Netlify functions, so it must import nothing but \`viem\` types — see
 * the header comment in \`./contests\`.
 */
export const ORIGINALITY_R3_V3_PARENT_MARKET_ID: Address = "${lc(created.parent.market)}";

/** The parent's Invalid outcome token (SER-INVALID), its last wrapped token. */
export const ORIGINALITY_R3_V3_PARENT_INVALID_TOKEN: Address = "${lc(created.parent.wrappedTokens[3])}";

export interface OriginalityR3V3MiddleMarket {
  marketId: Address;
  /** The bundle token: this market's collateral, and what a merge of it returns. */
  collateralToken: Address;
  /** One token per repo in slot order, then Invalid — a complete set. */
  wrappedTokens: readonly Address[];
}

/** Index = bundle (0 = A, 1 = B, 2 = C). */
export const ORIGINALITY_R3_V3_MIDDLE_MARKETS: readonly OriginalityR3V3MiddleMarket[] = [`);
middles.forEach((m, i) => {
  out.push(`  {
    marketId: "${lc(m.market)}",
    collateralToken: "${lc(created.parent.wrappedTokens[i])}",
    wrappedTokens: [
${m.wrappedTokens.map((t) => `      "${lc(t)}",`).join("\n")}
    ],
  },`);
});
out.push(`];

export interface OriginalityR3V3Market {
  repo: string;
  address: Address;
  /** 0 = Bundle A, 1 = Bundle B, 2 = Bundle C — which middle market the repo sits in. */
  bundle: 0 | 1 | 2;
  /** The repo's outcome slot in that middle market — the market's \`parentOutcome\`. */
  slot: number;
}

export const ORIGINALITY_R3_V3_MARKETS: readonly OriginalityR3V3Market[] = [`);
for (const r of rows) out.push(`  { repo: "${r.repo}", address: "${r.address}", bundle: ${r.bundle}, slot: ${r.slot} },`);
out.push(`];

export const ORIGINALITY_R3_V3_MARKET_IDS: readonly Address[] = ORIGINALITY_R3_V3_MARKETS.map(
  (market) => market.address,
);
`);
process.stdout.write(out.join("\n"));
